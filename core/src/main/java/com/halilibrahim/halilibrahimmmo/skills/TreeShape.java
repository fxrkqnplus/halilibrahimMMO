package com.halilibrahim.halilibrahimmmo.skills;

import org.bukkit.Material;
import org.bukkit.Tag;
import org.bukkit.block.Block;

import java.util.ArrayDeque;
import java.util.Deque;
import java.util.HashSet;
import java.util.Set;

/**
 * Decides whether a broken log is the root of a real, world-grown tree rather
 * than part of a building.
 *
 * <p>The reason this exists: "is it a log, and is there no log directly
 * beneath it" is true of a village house's corner pillar just as much as it is
 * of an oak trunk, so tree felling used to bring down the load-bearing timber
 * of naturally-generated houses. A player-placed log is already excluded
 * elsewhere by the placed-block tracker, but a village is generated by the
 * world, so nothing about its provenance distinguishes it from a tree.</p>
 *
 * <p>What actually distinguishes them is shape, and this class tests three
 * things a tree always has and a building never does:</p>
 *
 * <ol>
 *   <li><strong>It grows out of soil.</strong> The block under the root log
 *       must be something a tree can actually take root in - dirt and its
 *       family, moss, mud, sand/clay for mangroves, or nylium/soul soil for
 *       the nether fungi. A house pillar stands on planks, stone, a slab, a
 *       path or the house's own floor.</li>
 *   <li><strong>It is crowned with foliage.</strong> Leaves (or wart blocks
 *       and shroomlights, for the nether "trees") must touch the trunk itself,
 *       and enough of them that a single decorative leaf block next to a wall
 *       is not mistaken for a canopy.</li>
 *   <li><strong>It is not built into anything.</strong> A trunk touching
 *       planks, stairs, slabs, fences, doors, windows or crafting stations is
 *       structural timber, whatever else is growing nearby - this is what
 *       keeps a house standing in the middle of a forest safe.</li>
 * </ol>
 *
 * <p>All three must hold. The scan is bounded by {@link #MAX_SCANNED_LOGS} and
 * only ever reads blocks immediately around an already-loaded trunk, so it
 * costs nothing on the overwhelmingly common case of breaking a single log
 * that fails the very first check.</p>
 */
public final class TreeShape {

    /** Upper bound on the trunk flood-fill, independent of any configured felling limit. */
    private static final int MAX_SCANNED_LOGS = 64;
    /** How many canopy blocks must touch the trunk before it counts as a crown. */
    private static final int REQUIRED_CANOPY_BLOCKS = 4;

    /** Blocks a tree can be rooted in. */
    private static final Set<Material> SOILS = Set.of(
            Material.DIRT, Material.GRASS_BLOCK, Material.COARSE_DIRT, Material.PODZOL, Material.MYCELIUM,
            Material.ROOTED_DIRT, Material.MOSS_BLOCK, Material.PALE_MOSS_BLOCK, Material.MUD,
            Material.MUDDY_MANGROVE_ROOTS, Material.CLAY, Material.SAND, Material.RED_SAND, Material.SNOW_BLOCK,
            Material.CRIMSON_NYLIUM, Material.WARPED_NYLIUM, Material.SOUL_SAND, Material.SOUL_SOIL,
            Material.FARMLAND, Material.GRAVEL
    );

    /** Nether fungus "foliage" - not covered by {@link Tag#LEAVES}. */
    private static final Set<Material> FUNGUS_CANOPY = Set.of(
            Material.NETHER_WART_BLOCK, Material.WARPED_WART_BLOCK, Material.SHROOMLIGHT
    );

    /** Blocks that only ever appear because somebody built something. */
    private static final Set<Material> BUILT_MARKERS = Set.of(
            Material.CRAFTING_TABLE, Material.FLETCHING_TABLE, Material.SMITHING_TABLE, Material.CARTOGRAPHY_TABLE,
            Material.LOOM, Material.BARREL, Material.SMOKER, Material.BLAST_FURNACE, Material.FURNACE,
            Material.COMPOSTER, Material.LECTERN, Material.STONECUTTER, Material.GRINDSTONE, Material.BELL,
            Material.CAULDRON, Material.WATER_CAULDRON, Material.LANTERN, Material.CHEST, Material.BOOKSHELF,
            Material.LADDER, Material.SCAFFOLDING, Material.TORCH, Material.WALL_TORCH
    );

    private TreeShape() {
        throw new UnsupportedOperationException("TreeShape is a static utility class");
    }

    /**
     * @param root the log the player just broke
     * @return {@code true} only if {@code root} is the base of a naturally
     *         grown tree, so felling it is safe
     */
    public static boolean isNaturalTreeRoot(Block root) {
        if (!Tag.LOGS.isTagged(root.getType())) {
            return false;
        }
        // A log with another log under it is mid-trunk: felling from there
        // would turn every single log break into a cascade.
        if (Tag.LOGS.isTagged(root.getRelative(0, -1, 0).getType())) {
            return false;
        }
        if (!SOILS.contains(root.getRelative(0, -1, 0).getType())) {
            return false;
        }
        return hasCanopy(collectTrunk(root));
    }

    /** Flood-fills the trunk through same-type logs only, so a wall of mixed timber is never treated as one tree. */
    private static Set<Block> collectTrunk(Block root) {
        Material logType = root.getType();
        Set<Block> trunk = new HashSet<>();
        Deque<Block> pending = new ArrayDeque<>();
        pending.add(root);
        while (!pending.isEmpty() && trunk.size() < MAX_SCANNED_LOGS) {
            Block block = pending.removeFirst();
            if (block.getType() != logType || !trunk.add(block)) {
                continue;
            }
            pending.add(block.getRelative(1, 0, 0));
            pending.add(block.getRelative(-1, 0, 0));
            pending.add(block.getRelative(0, 1, 0));
            pending.add(block.getRelative(0, -1, 0));
            pending.add(block.getRelative(0, 0, 1));
            pending.add(block.getRelative(0, 0, -1));
        }
        return trunk;
    }

    /**
     * Walks the 26 neighbours of every trunk log once, counting foliage and
     * bailing out the moment anything man-made shows up. Both answers come out
     * of the same pass because a trunk that touches a plank is disqualified no
     * matter how many leaves it also touches.
     */
    private static boolean hasCanopy(Set<Block> trunk) {
        int canopy = 0;
        for (Block log : trunk) {
            for (int x = -1; x <= 1; x++) {
                for (int y = -1; y <= 1; y++) {
                    for (int z = -1; z <= 1; z++) {
                        Block neighbour = log.getRelative(x, y, z);
                        if (trunk.contains(neighbour)) {
                            continue;
                        }
                        Material type = neighbour.getType();
                        if (isBuildingMaterial(type)) {
                            return false;
                        }
                        if (Tag.LEAVES.isTagged(type) || FUNGUS_CANOPY.contains(type)) {
                            canopy++;
                        }
                    }
                }
            }
        }
        return canopy >= REQUIRED_CANOPY_BLOCKS;
    }

    private static boolean isBuildingMaterial(Material type) {
        return Tag.PLANKS.isTagged(type)
                || Tag.WOODEN_STAIRS.isTagged(type)
                || Tag.WOODEN_SLABS.isTagged(type)
                || Tag.WOODEN_FENCES.isTagged(type)
                || Tag.FENCE_GATES.isTagged(type)
                || Tag.DOORS.isTagged(type)
                || Tag.TRAPDOORS.isTagged(type)
                || Tag.WOODEN_PRESSURE_PLATES.isTagged(type)
                || Tag.STAIRS.isTagged(type)
                || Tag.SLABS.isTagged(type)
                || Tag.WALLS.isTagged(type)
                || Tag.BEDS.isTagged(type)
                || Tag.WOOL.isTagged(type)
                || Tag.WOOL_CARPETS.isTagged(type)
                || Tag.IMPERMEABLE.isTagged(type)
                || BUILT_MARKERS.contains(type);
    }
}
